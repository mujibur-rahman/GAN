#!/usr/bin/env python3
"""
Parameter scaling in the number of geographic partitions P.

The paper claims the generator backbone is constant in P while only the
geo-embedding table grows. That claim is currently argued analytically and
never measured, which is a gap given it is the claim in the title. This
computes both curves so Section VII-B can show it.

Two architectures are compared at matched capacity:

  shared     one geo-conditioned CVAE; conditioning enters as an embedding
             lookup, so the encoder/decoder weights are shared across all
             partitions. Cost: backbone + P*d_g + K*d_k.

  per_part   the naive alternative the paper rules out: one CVAE per
             partition. Cost: P * (backbone + K*d_k).

Defaults match the GeoLife configuration described in the paper (d=32 feature
dim, K=7 classes, 3,464 parameters at P=18). Override to match your actual
configuration, then verify `--check` reproduces your real parameter count
before putting the numbers in the paper.

Usage
    python3 param_scaling.py --check 3464
    python3 param_scaling.py --p-values 6 12 18 36 72 --out tab_scaling.tex
"""

import argparse


def cvae_backbone(d_feat, d_hidden, d_z, d_cond):
    """Encoder + decoder weights of the conditional VAE, excluding embedding
    tables. Encoder: [h ; c] -> hidden -> (mu, logvar). Decoder: [z ; c] ->
    hidden -> h_hat. Biases included."""
    enc_in = d_feat + d_cond
    enc = enc_in * d_hidden + d_hidden          # input -> hidden
    enc += 2 * (d_hidden * d_z + d_z)           # hidden -> mu, logvar
    dec_in = d_z + d_cond
    dec = dec_in * d_hidden + d_hidden          # [z;c] -> hidden
    dec += d_hidden * d_feat + d_feat           # hidden -> h_hat
    return enc + dec


def shared_total(P, K, d_feat, d_hidden, d_z, d_g, d_k):
    return cvae_backbone(d_feat, d_hidden, d_z, d_g + d_k) + P * d_g + K * d_k


def per_partition_total(P, K, d_feat, d_hidden, d_z, d_k):
    # no geo embedding needed: partition identity is implicit in which
    # generator you pick, which is exactly why the count multiplies.
    return P * (cvae_backbone(d_feat, d_hidden, d_z, d_k) + K * d_k)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--p-values", type=int, nargs="+", default=[6, 12, 18, 36, 72])
    ap.add_argument("--K", type=int, default=7, help="number of task classes")
    ap.add_argument("--d-feat", type=int, default=32, help="penultimate feature dim")
    ap.add_argument("--d-hidden", type=int, default=32)
    ap.add_argument("--d-z", type=int, default=16, help="latent dim")
    ap.add_argument("--d-g", type=int, default=8, help="geo embedding dim")
    ap.add_argument("--d-k", type=int, default=8, help="class embedding dim")
    ap.add_argument("--check", type=int, default=None,
                    help="assert the shared total at --check-p equals this")
    ap.add_argument("--check-p", type=int, default=18)
    ap.add_argument("--out")
    args = ap.parse_args()

    bb = cvae_backbone(args.d_feat, args.d_hidden, args.d_z, args.d_g + args.d_k)
    print(f"config: d_feat={args.d_feat} d_hidden={args.d_hidden} d_z={args.d_z} "
          f"d_g={args.d_g} d_k={args.d_k} K={args.K}")
    print(f"shared backbone (constant in P): {bb:,} parameters\n")

    if args.check is not None:
        got = shared_total(args.check_p, args.K, args.d_feat, args.d_hidden,
                           args.d_z, args.d_g, args.d_k)
        status = "MATCH" if got == args.check else "MISMATCH"
        print(f"[{status}] shared total at P={args.check_p}: {got:,} "
              f"(expected {args.check:,})")
        if got != args.check:
            print("  -> adjust --d-hidden/--d-z/--d-g/--d-k until this matches your")
            print("     implementation, otherwise the table will not match Table I.\n")
        else:
            print()

    rows = []
    for P in args.p_values:
        s = shared_total(P, args.K, args.d_feat, args.d_hidden, args.d_z, args.d_g, args.d_k)
        n = per_partition_total(P, args.K, args.d_feat, args.d_hidden, args.d_z, args.d_k)
        rows.append((P, bb, P * args.d_g, s, n, n / s))
        print(f"  P={P:4d}  shared {s:9,}  (backbone {bb:,} + geo table {P*args.d_g:,})"
              f"   per-partition {n:10,}   ratio {n/s:7.1f}x")

    tex = ["% generated by param_scaling.py",
           "\\begin{tabular}{lrrrr}", "\\toprule",
           "\\textbf{$P$} & \\textbf{Backbone} & \\textbf{Geo table} & "
           "\\textbf{Shared total} & \\textbf{Per-partition} \\\\", "\\midrule"]
    for P, b, g, s, n, _ in rows:
        tex.append(f"{P} & {b:,} & {g:,} & {s:,} & {n:,} \\\\")
    tex += ["\\bottomrule", "\\end{tabular}",
            "% Backbone is constant in P; only the geo table grows, as O(P d_g)."]

    text = "\n".join(tex)
    if args.out:
        with open(args.out, "w") as fh:
            fh.write(text)
        print(f"\n[written] {args.out}")
    else:
        print("\n" + text)


if __name__ == "__main__":
    main()
