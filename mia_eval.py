#!/usr/bin/env python3
"""
Membership-inference evaluation for the Geo-CVAE VTC paper.

Fixes the two problems the reviewer-side read found in Table II:

  1. Table II currently applies a *different* attack to each method, so its
     columns cannot be read as a privacy ranking. This script separates the
     two kinds of measurement explicitly:

        --family common    one attack applied identically to every arm
                           (task-model loss/confidence threshold). This is the
                           comparable column, and the only one that supports
                           a statement about which method leaks more.

        --family specific  generator-specific attacks (CVAE reconstruction gap,
                           AC-GAN discriminator score). Reported per method as
                           "what surface exists", never cross-compared.

  2. Table II has no no-replay control, so it cannot show that replay *adds*
     exposure. Include an arm named by --control (default "no_replay") in the
     common family and the script reports each arm's delta over it.

AUC alone understates worst-case exposure, so TPR at a low FPR is reported
alongside, alluded with a bootstrap CI so a 0.71 vs 0.74 gap can be judged.

Input schema
------------
scores.csv   arm,attack,family,is_member,score

  arm        no_replay | ewc | er | ac_gan | geo_cvae
  attack     loss_threshold | recon_gap | d_score
  family     common | specific
  is_member  1 or 0
  score      higher must mean "more likely a member". For the CVAE
             reconstruction gap, members have LOWER error, so negate it when
             writing the CSV (or pass --flip recon_gap).

Usage
    python3 mia_eval.py scores.csv --out tab_mia.tex --flip recon_gap
"""

import argparse
import csv
import sys
from collections import defaultdict

import numpy as np
from sklearn.metrics import roc_auc_score, roc_curve


def bootstrap_auc(y, s, n_boot=2000, seed=0):
    """Percentile bootstrap CI for AUC, resampling members and non-members
    separately so class balance is preserved in every replicate."""
    rng = np.random.default_rng(seed)
    y, s = np.asarray(y), np.asarray(s)
    pos, neg = np.flatnonzero(y == 1), np.flatnonzero(y == 0)
    if len(pos) == 0 or len(neg) == 0:
        return (float("nan"), float("nan"))
    out = []
    for _ in range(n_boot):
        idx = np.concatenate([rng.choice(pos, len(pos), replace=True),
                              rng.choice(neg, len(neg), replace=True)])
        try:
            out.append(roc_auc_score(y[idx], s[idx]))
        except ValueError:
            continue
    if not out:
        return (float("nan"), float("nan"))
    return (float(np.percentile(out, 2.5)), float(np.percentile(out, 97.5)))


def tpr_at_fpr(y, s, target):
    fpr, tpr, _ = roc_curve(y, s)
    ok = fpr <= target
    return float(tpr[ok].max()) if ok.any() else 0.0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("path")
    ap.add_argument("--out")
    ap.add_argument("--control", default="no_replay",
                    help="arm representing the task model with no replay component")
    ap.add_argument("--fpr", type=float, default=0.01,
                    help="low-FPR operating point for TPR reporting")
    ap.add_argument("--flip", nargs="*", default=[],
                    help="attack names whose raw score is lower-for-members")
    ap.add_argument("--boot", type=int, default=2000)
    args = ap.parse_args()

    with open(args.path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        sys.exit("no rows")

    data = defaultdict(lambda: {"y": [], "s": []})
    meta = {}
    for r in rows:
        arm, attack = r["arm"].strip(), r["attack"].strip()
        fam = r.get("family", "").strip() or "common"
        key = (fam, arm, attack)
        sc = float(r["score"])
        if attack in args.flip:
            sc = -sc
        data[key]["y"].append(int(float(r["is_member"])))
        data[key]["s"].append(sc)
        meta[key] = fam

    results = {}
    for key, d in data.items():
        y, s = np.array(d["y"]), np.array(d["s"])
        if len(set(y.tolist())) < 2:
            print(f"! {key}: only one class present, skipped")
            continue
        auc = roc_auc_score(y, s)
        lo, hi = bootstrap_auc(y, s, args.boot)
        results[key] = {
            "auc": auc, "lo": lo, "hi": hi,
            "tpr": tpr_at_fpr(y, s, args.fpr),
            "n_pos": int((y == 1).sum()), "n_neg": int((y == 0).sum()),
        }

    common = {k: v for k, v in results.items() if k[0] == "common"}
    specific = {k: v for k, v in results.items() if k[0] == "specific"}

    tex = ["% generated by mia_eval.py"]

    # ---- comparable family -------------------------------------------------
    if common:
        print("=== common attack (comparable across arms) ===")
        ctrl = next((v for (f, a, _), v in common.items() if a == args.control), None)
        if ctrl is None:
            print(f"! no '{args.control}' arm found. Without it you cannot claim")
            print("  replay adds leakage; the table shows absolute levels only.")
        tex += [
            "\\begin{tabular}{lccc}", "\\toprule",
            "\\textbf{Arm} & \\textbf{AUC (95\\% CI)} & "
            f"\\textbf{{TPR@{args.fpr:.0%} FPR}} & \\textbf{{$\\Delta$AUC}} \\\\".replace("%", "\\%"),
            "\\midrule",
        ]
        for (f, arm, attack), v in sorted(common.items(), key=lambda kv: kv[0][1]):
            delta = "--" if ctrl is None or arm == args.control else f"{v['auc']-ctrl['auc']:+.3f}"
            print(f"  {arm:14s} AUC {v['auc']:.3f} [{v['lo']:.3f},{v['hi']:.3f}]"
                  f"  TPR@{args.fpr:.0%} {v['tpr']:.3f}  dAUC {delta}")
            tex.append(f"{arm} & {v['auc']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] "
                       f"& {v['tpr']:.3f} & {delta} \\\\")
        tex += ["\\bottomrule", "\\end{tabular}", ""]

        if ctrl is not None:
            print("\n  interpretation guide:")
            print("   dAUC ~ 0 and overlapping CIs -> replay adds no measurable")
            print("     leakage over the task model; say so plainly, it is a")
            print("     result in your favour, not a null.")
            print("   dAUC > 0 with separated CIs  -> the generator is a real")
            print("     additional surface and the privacy section is load-bearing.")

    # ---- generator-specific family ----------------------------------------
    if specific:
        print("\n=== generator-specific attacks (NOT cross-comparable) ===")
        tex += [
            "\\begin{tabular}{llcc}", "\\toprule",
            "\\textbf{Arm} & \\textbf{Attack} & \\textbf{AUC (95\\% CI)} & "
            f"\\textbf{{TPR@{args.fpr:.0%} FPR}} \\\\".replace("%", "\\%"),
            "\\midrule",
        ]
        for (f, arm, attack), v in sorted(specific.items(), key=lambda kv: kv[0][1]):
            print(f"  {arm:14s} {attack:14s} AUC {v['auc']:.3f} "
                  f"[{v['lo']:.3f},{v['hi']:.3f}]  TPR@{args.fpr:.0%} {v['tpr']:.3f}")
            tex.append(f"{arm} & {attack.replace('_',' ')} & "
                       f"{v['auc']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] & {v['tpr']:.3f} \\\\")
        tex += ["\\bottomrule", "\\end{tabular}",
                "% Different attacks per arm: read as available surface, not a ranking."]
        print("\n  these rows describe which surface each generator exposes.")
        print("  do not rank methods on them; that is what the common family is for.")

    text = "\n".join(tex)
    if args.out:
        with open(args.out, "w") as fh:
            fh.write(text)
        print(f"\n[written] {args.out}")
    else:
        print("\n" + text)


if __name__ == "__main__":
    main()
